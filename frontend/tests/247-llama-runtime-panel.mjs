import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const panel = readFileSync(new URL('../src/components/coding/LocalModelPanel.tsx', import.meta.url), 'utf8');
const api = readFileSync(new URL('../src/api/llamaRuntime.ts', import.meta.url), 'utf8');
const source = panel.match(/export function buttons\([\s\S]*?\n}/)[0].replace(/s: LlamaStatus \| null, busy: boolean/, 's, busy');
const busyStatus = s => s?.reason_code === 'LLAMACPP_LOADING' || s?.reason_code === 'LLAMACPP_RECOVERING';
const buttons = new Function('busyStatus', `${source.replace('export ', '')}; return buttons`)(busyStatus);
const stopped = { configured: true, runtime_reachable: false, spawned_by_jarvis: false };
const running = { ...stopped, runtime_reachable: true, spawned_by_jarvis: true };
assert.deepEqual(buttons(null, false), { start: false, stop: false, restart: false });
assert.deepEqual(buttons({ ...stopped, configured: false }, false), { start: false, stop: false, restart: false });
assert.deepEqual(buttons(stopped, false), { start: true, stop: false, restart: false });
assert.deepEqual(buttons(running, false), { start: false, stop: true, restart: true });
assert.deepEqual(buttons(running, true), { start: false, stop: false, restart: false });
assert.deepEqual(buttons({ ...running, reason_code: 'LLAMACPP_LOADING' }, false), { start: false, stop: false, restart: false });
assert.match(panel, /action !== "start" && !window\.confirm/);
assert.match(panel, /actionLock\.current = true/);
assert.match(panel, /actionLock\.current \|\|/);
assert.match(panel, /Last known status follows/);
assert.match(panel, /role="alert">Error:/);
assert.match(panel, /Not configured.*status\.message/);
assert.match(panel, /useEffect\(\(\) => \{ void refresh\(\)/);
assert.doesNotMatch(panel, /useEffect[^\n]*controlLlama/);
assert.match(api, /action \? \{ method: "POST" \} : undefined/);
assert.match(panel, /visibilityState === "visible"/);
console.log('247 local model panel checks passed');
