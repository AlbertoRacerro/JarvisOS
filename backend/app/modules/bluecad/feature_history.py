FEATURE_SEQUENCE_VERSION = "feature_sequence_v1"
ARTIFACT_PRODUCER = "Generated by deterministic BLUECAD feature history compiler."
_STRICT = ConfigDict(extra="forbid", allow_inf_nan=False)
_PARAMS = {
    "tube_run": ("outer_d_mm", "wall_t_mm", "length_mm"),
    "bend": ("outer_d_mm", "wall_t_mm", "bend_radius_mm", "angle_deg"),
    "manifold": ("outer_d_mm", "wall_t_mm", "length_mm", "branch_count", "branch_outer_d_mm"),
    "serpentine": ("outer_d_mm", "wall_t_mm", "segment_length_mm", "segment_count", "bend_radius_mm"),
}
_COUNTS = {"branch_count", "segment_count"}


class FeatureHistoryError(ValueError):
    def __init__(self, code: str, message: str, status_code: int = 422) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.status_code = status_code


class FeatureParameter(BaseModel):
    model_config = _STRICT
    name: str = Field(pattern=r"^[a-zA-Z_][a-zA-Z0-9_]*$", max_length=64)
    value: float = Field(gt=0)
    unit: Literal["mm", "deg"] = "mm"


class FeatureConnectTo(BaseModel):
    model_config = _STRICT
    from_port: str = Field(min_length=1)
    to_feature_id: str = Field(min_length=1)
    to_port: str = Field(min_length=1)


class FeatureFrame(BaseModel):
    model_config = _STRICT
    origin: tuple[float, float, float]
    direction: tuple[float, float, float]


class FeatureStep(BaseModel):
    model_config = _STRICT
    feature_id: str = Field(min_length=1, pattern=r"^[a-zA-Z0-9_-]+$")
    enabled: bool = True
    kind: Literal["tube_run", "bend", "manifold", "serpentine"]
    params: dict[str, Any]
    frame: FeatureFrame | None = None
    connect_to: FeatureConnectTo | None = None


class FeatureSequence(BaseModel):
    model_config = _STRICT
    schema_version: Literal["feature_sequence_v1"] = FEATURE_SEQUENCE_VERSION
    parameters: list[FeatureParameter] = Field(default_factory=list)
    features: list[FeatureStep] = Field(min_length=1)


def _resolved(feature: FeatureStep, parameters: dict[str, FeatureParameter]) -> dict[str, float | int]:
    if set(feature.params) != set(_PARAMS[feature.kind]):
        raise FeatureHistoryError("feature_geometry_invalid", f"{feature.feature_id} has missing or unexpected parameters.")
    result: dict[str, float | int] = {}
    for key, raw in feature.params.items():
        if isinstance(raw, dict):
            if set(raw) != {"$param"} or not isinstance(raw["$param"], str):
                raise FeatureHistoryError("feature_geometry_invalid", f"Invalid parameter reference in {feature.feature_id}.")
            parameter = parameters.get(raw["$param"])
            if parameter is None:
                raise FeatureHistoryError("unknown_parameter", f"Unknown parameter {raw['$param']}.")
            expected_unit = "deg" if key == "angle_deg" else "mm"
            if key not in _COUNTS and parameter.unit != expected_unit:
                raise FeatureHistoryError("feature_geometry_invalid", f"{key} requires {expected_unit}.")
            raw = parameter.value
        if isinstance(raw, bool) or not isinstance(raw, (int, float)) or not math.isfinite(raw):
            raise FeatureHistoryError("feature_geometry_invalid", f"{key} must be a finite number.")
        if key in _COUNTS:
            if int(raw) != raw:
                raise FeatureHistoryError("feature_geometry_invalid", f"{key} must be an integer.")
            result[key] = int(raw)
        else:
            result[key] = float(raw)
    return result


def compile_feature_sequence(
    sequence: FeatureSequence | Mapping[str, Any],
) -> tuple[dict[str, Any], dict[str, Any], str]:
    try:
        seq = sequence if isinstance(sequence, FeatureSequence) else FeatureSequence.model_validate(sequence)
    except ValidationError as exc:
        raise FeatureHistoryError("feature_geometry_invalid", str(exc)) from exc
    parameters: dict[str, FeatureParameter] = {}
    for parameter in seq.parameters:
        if parameter.name in parameters:
            raise FeatureHistoryError("duplicate_parameter", f"Duplicate parameter {parameter.name}.")
        parameters[parameter.name] = parameter
    ids: set[str] = set()
    for feature in seq.features:
        if feature.feature_id in ids:
            raise FeatureHistoryError("duplicate_feature_id", f"Duplicate feature_id {feature.feature_id}.")
        ids.add(feature.feature_id)
    enabled = [feature for feature in seq.features if feature.enabled]
    if not enabled:
        raise FeatureHistoryError("no_enabled_features", "At least one feature must be enabled.")
    parts: list[dict[str, Any]] = []
    connections: list[dict[str, str]] = []
    exits: dict[str, str] = {}
    for feature in enabled:
        values = _resolved(feature, parameters)
        try:
            if feature.kind == "tube_run":
                p = TubeTemplateParams.model_validate(values)
                new_parts = [{"part_id": feature.feature_id, "kind": "tube_run", "params":
                              {"outer_d": p.outer_d_mm, "wall_t": p.wall_t_mm, "length": p.length_mm}}]
                internal: list[dict[str, str]] = []
                entry = exit_part = feature.feature_id
            elif feature.kind == "bend":
                outer, wall = values["outer_d_mm"], values["wall_t_mm"]
                radius, angle = values["bend_radius_mm"], values["angle_deg"]
                TubeTemplateParams.model_validate({"outer_d_mm": outer, "wall_t_mm": wall, "length_mm": 1})
                if not 1 <= radius <= 5000 or radius < outer or not 0 < angle <= 180:
                    raise ValueError("Bend radius or angle is outside the supported bounds.")
                new_parts = [{"part_id": feature.feature_id, "kind": "bend", "params":
                              {"outer_d": outer, "wall_t": wall, "bend_radius": radius,
                               "angle": math.radians(angle)}}]
                internal = []
                entry = exit_part = feature.feature_id
            elif feature.kind == "manifold":
                p = ManifoldTemplateParams.model_validate(values)
                new_parts = [{"part_id": feature.feature_id, "kind": "manifold", "params":
                              {"outer_d_main": p.outer_d_mm, "wall_t": p.wall_t_mm, "length": p.length_mm,
                               "n_out": p.branch_count, "out_d": p.branch_outer_d_mm,
                               "out_wall_t": p.wall_t_mm, "spacing": p.length_mm / (p.branch_count + 1)}}]
                internal = []
                entry = exit_part = feature.feature_id
            else:
                p = SerpentineTemplateParams.model_validate(values)
                new_parts, internal = _serpentine_parts(p)
                for part in new_parts:
                    part["part_id"] = f"{feature.feature_id}_{part['part_id']}"
                internal = [{"from": f"{feature.feature_id}_{link['from']}",
                             "to": f"{feature.feature_id}_{link['to']}"} for link in internal]
                entry, exit_part = f"{feature.feature_id}_run_1", f"{feature.feature_id}_run_{p.segment_count}"
        except (ValidationError, ValueError) as exc:
            raise FeatureHistoryError("feature_geometry_invalid", str(exc)) from exc
        if feature.frame is not None:
            new_parts[0]["frame"] = feature.frame.model_dump(mode="json")
        if feature.connect_to is not None:
            target = exits.get(feature.connect_to.to_feature_id)
            if target is None:
                raise FeatureHistoryError("invalid_connection_target", "Connection target must be an earlier enabled feature.")
            connections.append({"from": f"{target}.{feature.connect_to.to_port}",
                                "to": f"{entry}.{feature.connect_to.from_port}"})
        parts.extend(new_parts)
        connections.extend(internal)
        exits[feature.feature_id] = exit_part
    canonical_sequence = seq.model_dump(mode="json")
    try:
        spec = canonicalize_geometry_spec({"spec_version": "bluecad_geometry_spec_v0_1",
                                           "name": "feature_history", "parts": parts,
                                           "connections": connections})
        digest = "sha256:" + hashlib.sha256(canonical_json(canonical_sequence).encode()).hexdigest()
    except (SpecValidationError, ValidationError) as exc:
        raise FeatureHistoryError("feature_geometry_invalid", str(exc)) from exc
    return canonical_sequence, spec, digest


def synthesize_feature_sequence_from_spec(spec: Mapping[str, Any]) -> FeatureSequence | None:
    parts = spec.get("parts")
    if not isinstance(parts, list) or not parts:
        return None
    if not all(isinstance(part, dict) for part in parts):
        return None
    if len(parts) > 1:
        count = (len(parts) + 1) // 2
        first = parts[0]
        if len(parts) != 2 * count - 1 or first.get("kind") != "tube_run":
            return None
        params = first.get("params", {})
        bend = parts[1].get("params", {}) if count > 1 else {}
        values = {"outer_d_mm": params.get("outer_d"), "wall_t_mm": params.get("wall_t"),
                  "segment_length_mm": params.get("length"), "segment_count": count,
                  "bend_radius_mm": bend.get("bend_radius", params.get("outer_d"))}
        try:
            template = SerpentineTemplateParams.model_validate(values)
            expected_parts, expected_connections = _serpentine_parts(template)
            if parts != expected_parts or spec.get("connections", []) != expected_connections:
                return None
            sequence = FeatureSequence(
                parameters=[FeatureParameter(name=k, value=v) for k, v in values.items()],
                features=[FeatureStep(feature_id="serpentine", kind="serpentine",
                                      params={k: {"$param": k} for k in values})],
            )
            compile_feature_sequence(sequence)
            return sequence
        except (ValidationError, FeatureHistoryError, ValueError, TypeError):
            return None
    if spec.get("connections"):
        return None
    part = parts[0]
    kind = part.get("kind")
    if kind not in {"tube_run", "bend", "manifold"}:
        return None
    p = part.get("params", {})
    if kind == "tube_run":
        values = {"outer_d_mm": p.get("outer_d"), "wall_t_mm": p.get("wall_t"), "length_mm": p.get("length")}
    elif kind == "bend":
        values = {"outer_d_mm": p.get("outer_d"), "wall_t_mm": p.get("wall_t"),
                  "bend_radius_mm": p.get("bend_radius"), "angle_deg": p.get("angle")}
    else:
        values = {"outer_d_mm": p.get("outer_d_main"), "wall_t_mm": p.get("wall_t"),
                  "length_mm": p.get("length"), "branch_count": p.get("n_out"),
                  "branch_outer_d_mm": p.get("out_d")}
    try:
        if kind == "bend":
            values["angle_deg"] = math.degrees(values["angle_deg"])
        seq = FeatureSequence(parameters=[FeatureParameter(name=k, value=v, unit="deg" if k == "angle_deg" else "mm")
                                          for k, v in values.items()],
                              features=[FeatureStep(feature_id=part["part_id"], kind=kind,
                                                    params={k: {"$param": k} for k in values},
                                                    frame=part.get("frame"))])
        compile_feature_sequence(seq)
    except (ValidationError, FeatureHistoryError, KeyError, TypeError, ValueError):
        return None
    return seq


def create_feature_history_candidate(
    workspace_id: str, sequence: FeatureSequence | Mapping[str, Any], *, parent_candidate_id: str | None = None,
) -> tuple[BluecadCandidateRead, dict[str, Any], dict[str, Any], str]:
    canonical_seq, spec, digest = compile_feature_sequence(sequence)
    candidate_id, attempt_id, now = str(uuid4()), str(uuid4()), utc_now()
    brief = f"Feature history {digest}"
    with open_sqlite_connection() as connection:
        _require_workspace(connection, workspace_id)
        connection.execute(
            "INSERT INTO bluecad_candidates (id, workspace_id, brief_text, brief_digest, status, parked_reason, "
            "spec_artifact_id, glb_artifact_id, report_artifact_id, promoted_decision_id, origin, "
            "parent_candidate_id, loop_config_json, created_at, updated_at, notes) "
            "VALUES (?, ?, ?, ?, 'generating', NULL, NULL, NULL, NULL, NULL, 'feature_history', ?, '{}', ?, ?, ?)",
            (candidate_id, workspace_id, brief, brief_digest(brief), parent_candidate_id, now, now,
             f"feature_sequence_version={FEATURE_SEQUENCE_VERSION}"),
        )
        connection.execute(
            "INSERT INTO bluecad_attempts (id, candidate_id, attempt_no, route_class, proposal_ai_job_id, "
            "proposal_outcome, build_outcome, validation_verdict, spec_artifact_id, report_artifact_id, "
            "manifest_artifact_id, started_at, finished_at, error_detail_json) "
            "VALUES (?, ?, 1, 'deterministic:feature_history', NULL, 'not_applicable', NULL, NULL, "
            "NULL, NULL, NULL, ?, NULL, ?)",
            (attempt_id, candidate_id, now, json.dumps({"sequence_digest": digest}, sort_keys=True)),
        )
        connection.commit()
    try:
        build_geometry_candidate(workspace_id, candidate_id, attempt_id, spec,
                                 producer_notes=ARTIFACT_PRODUCER,
                                 failure_reason="feature_history_build_failed",
                                 timeout_s=template_build_timeout_s(spec))
    except Exception as exc:
        park_candidate(candidate_id, "feature_history_build_failed", notes=f"execution_error={type(exc).__name__}")
        raise FeatureHistoryError("feature_history_build_failed", "Feature history build did not complete.", 500) from exc
    candidate = get_candidate(workspace_id, candidate_id)
    if candidate is None:
        raise FeatureHistoryError("feature_history_persistence_inconsistent", "Feature history candidate is missing.", 500)
    return candidate, canonical_seq, spec, digest
