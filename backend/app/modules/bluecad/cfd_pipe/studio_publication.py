"""Publish a fitted reduced model through the Studio published-version owner (spec 216 contract 7).

A reduced model becomes a Studio calculation whose source is generated only from
the model's typed values and carries the whole versioned model as a constant, so
the Studio source digest binds the fit, validity, uncertainty and provenance.
Its test cases are the measured study points: each must reproduce the run's
Darcy factor within the fit uncertainty. Studio's own guards then decide
publication (a passing report for the current source and contract), and the
published version attaches to the component's Physics node and the 109/110
handoff like any other Studio calculation. No new store is introduced.
"""

from __future__ import annotations

import ast
import json

from app.modules.bluecad.cfd_pipe.reduced_model import PublicationRefused, ReducedModel, verify_version
from app.modules.studio import service as studio
from app.modules.studio.models import StudioCreate, StudioUpdate, TestCase, TestRequest
from app.modules.studio_runtime.runtime import status as runtime_status

# Relative slack on the Reynolds bounds: a measured point's velocity, rebuilt from its
# recorded Re, must land back inside the range it defined.
RANGE_SLACK = 1e-9
# Relative band within which a bore or fluid property counts as the validated value; the
# Studio input contract needs min < max, so the pinned values get this band as bounds.
SAME_VALUE = 1e-9
_PROPERTIES = ("diameter_m", "density_kg_m3", "dynamic_viscosity_pa_s")

_SOURCE = '''# Studio calculation generated from CFD reduced model {model_id}.
# Generated by the spec 216 publication operation from typed values; rerun and
# republish the study instead of editing this source.
REDUCED_MODEL_VERSION_ID = {version_id!r}
GEOMETRY_DIGEST = {geometry_digest!r}
REDUCED_MODEL_JSON = {model_json!r}
DIAMETER_M = {diameter!r}
DENSITY_KG_M3 = {density!r}
DYNAMIC_VISCOSITY_PA_S = {viscosity!r}
SAME_VALUE = {same!r}
RANGE_SLACK = {slack!r}
# (regime, Re min, Re max, a, b, combined relative uncertainty); f_D = a * Re**b
SEGMENTS = {segments!r}


def evaluate(mean_velocity: float, diameter: float, density: float, dynamic_viscosity: float) -> dict[str, float]:
    """Darcy factor, pressure gradient and wall shear inside the validated range only.

    Inputs:
        mean_velocity [m/s]
        diameter [m]
        density [kg/m**3]
        dynamic_viscosity [Pa*s]
    Outputs:
        reynolds [dimensionless]
        darcy_friction_factor [dimensionless]
        pressure_gradient [Pa/m]
        wall_shear_stress [Pa]
        relative_uncertainty [dimensionless]
    """
    for name, value, valid in (("diameter", diameter, DIAMETER_M), ("density", density, DENSITY_KG_M3),
                               ("dynamic_viscosity", dynamic_viscosity, DYNAMIC_VISCOSITY_PA_S)):
        if abs(value - valid) > SAME_VALUE * abs(valid):
            raise ValueError(name + " " + repr(value) + " differs from the validated " + repr(valid))
    reynolds = mean_velocity * diameter / (dynamic_viscosity / density)
    for regime, re_min, re_max, a, b, uncertainty in SEGMENTS:
        if re_min * (1.0 - RANGE_SLACK) <= reynolds <= re_max * (1.0 + RANGE_SLACK):
            darcy = a * reynolds ** b
            dynamic = density * mean_velocity ** 2
            return {{"reynolds": reynolds, "darcy_friction_factor": darcy,
                    "pressure_gradient": darcy * dynamic / (2.0 * diameter),
                    "wall_shear_stress": darcy * dynamic / 8.0, "relative_uncertainty": uncertainty}}
    raise ValueError("Re " + repr(reynolds) + " is outside the validated range " + repr(
        [(regime, re_min, re_max) for regime, re_min, re_max, _, _, _ in SEGMENTS]))


def main(inputs: dict[str, float]) -> dict[str, float]:
    return evaluate(mean_velocity=inputs['mean_velocity'], diameter=inputs['diameter'],
                    density=inputs['density'], dynamic_viscosity=inputs['dynamic_viscosity'])
'''


def _shared(model: ReducedModel, name: str) -> float:
    values = {getattr(segment.validity, name) for segment in model.segments}
    if len(values) != 1:
        raise PublicationRefused([f"segments differ in {name}; a Studio calculation holds one fluid and bore"])
    return values.pop()


def _check(model: ReducedModel) -> None:
    reasons = []
    if not verify_version(model):
        reasons.append("reduced model does not match its version identity")
    if not model.segments:
        reasons.append("reduced model has no segment")
    if reasons:
        raise PublicationRefused(reasons)


def studio_contract(model: ReducedModel) -> StudioCreate:
    """Studio inputs and outputs; bounds pin the bore and fluid and span the validated velocities."""
    _check(model)
    d, rho, mu = (_shared(model, name) for name in _PROPERTIES)
    nu = mu / rho
    u_min = min(s.validity.reynolds_min for s in model.segments) * nu / d * (1.0 - RANGE_SLACK)
    u_max = max(s.validity.reynolds_max for s in model.segments) * nu / d * (1.0 + RANGE_SLACK)
    spans = "; ".join(f"{s.regime} Re {s.validity.reynolds_min:.6g}–{s.validity.reynolds_max:.6g}"
                      for s in model.segments)

    def var(name: str, label: str, unit: str, description: str, low: float | None = None,
            high: float | None = None) -> dict:
        return {"name": name, "label": label, "unit": unit, "description": description,
                **({"min": low, "max": high} if low is not None else {})}

    def band(value: float) -> tuple[float, float]:
        return value * (1.0 - SAME_VALUE), value * (1.0 + SAME_VALUE)

    return StudioCreate.model_validate({
        "name": f"CFD reduced model {model.model_id}",
        "engineering_question": (f"What pressure gradient and wall shear does the CFD-qualified smooth tube "
                                 f"{model.model_id} give inside its validated range ({spans})?"),
        "inputs": [
            var("mean_velocity", "Mean velocity", "m/s", "Bulk velocity; Re outside the segments is refused.",
                u_min, u_max),
            var("diameter", "Bore", "m", "Validated bore of the qualified tube.", *band(d)),
            var("density", "Density", "kg/m**3", "Validated fluid density.", *band(rho)),
            var("dynamic_viscosity", "Dynamic viscosity", "Pa*s", "Validated fluid viscosity.", *band(mu)),
        ],
        "outputs": [
            var("reynolds", "Reynolds number", "dimensionless", "Bulk Reynolds number."),
            var("darcy_friction_factor", "Darcy friction factor", "dimensionless", "f_D = a Re^b of the segment."),
            var("pressure_gradient", "Pressure gradient", "Pa/m", "Developed-flow ΔP/L."),
            var("wall_shear_stress", "Wall shear stress", "Pa", "Mean developed wall shear."),
            var("relative_uncertainty", "Relative uncertainty", "dimensionless",
                "Discretization + fit + correlation, from the study."),
        ],
    })


def studio_source(model: ReducedModel) -> str:
    """Deterministic Studio source; every constant is a typed value of ``model``."""
    _check(model)
    d, rho, mu = (_shared(model, name) for name in _PROPERTIES)
    segments = tuple((s.regime, s.validity.reynolds_min, s.validity.reynolds_max, s.a, s.b, s.uncertainty.combined)
                     for s in model.segments)
    model_json = json.dumps(model.model_dump(mode="json"), sort_keys=True, separators=(",", ":"), allow_nan=False)
    return _SOURCE.format(model_id=model.model_id, version_id=model.version_id,
                          geometry_digest=model.geometry_digest, model_json=model_json, diameter=d, density=rho,
                          viscosity=mu, same=SAME_VALUE, slack=RANGE_SLACK, segments=segments)


def studio_tests(model: ReducedModel) -> TestRequest:
    """One case per measured point: the run's Darcy factor within the segment's fit uncertainty."""
    _check(model)
    d, rho, mu = (_shared(model, name) for name in _PROPERTIES)
    cases = []
    for segment in model.segments:
        for p in segment.points:
            velocity = p.reynolds * (mu / rho) / d
            tolerance = segment.uncertainty.fit * p.darcy_cfd * (1.0 + 1e-6) + 1e-12
            cases.append(TestCase(inputs={"mean_velocity": velocity, "diameter": d, "density": rho,
                                          "dynamic_viscosity": mu},
                                  expected_outputs={"darcy_friction_factor": p.darcy_cfd}, tolerance=tolerance))
    if len(cases) > 32:
        raise PublicationRefused([f"{len(cases)} study points exceed the 32 Studio test cases"])
    return TestRequest(cases=cases)


def provenance_note(model: ReducedModel) -> str:
    lines = [f"Reduced model {model.model_id} version {model.version_id}.", f"Form: {model.form}.",
             f"Geometry digest: {model.geometry_digest}."]
    for s in model.segments:
        u = s.uncertainty
        lines.append(
            f"{s.regime}: Re {s.validity.reynolds_min:.6g}–{s.validity.reynolds_max:.6g}, a={s.a:.6g}, b={s.b:.6g}, "
            f"reference {s.reference}, model {s.validity.turbulence_model or 'none'}/{s.validity.wall_treatment}; "
            f"uncertainty discretization {u.discretization:.3%} + fit {u.fit:.3%} + correlation "
            f"{u.correlation:.3%} = {u.combined:.3%}; study template {s.study_template_digest}.")
    for key, values in model.provenance.items():
        lines.append(f"{key}: {', '.join(values)}.")
    lines.append("Qualified within the stated range only; not a validated plant claim. Outside the range the "
                 "calculation refuses.")
    return "\n".join(lines)


def publish_to_studio(workspace_id: str, model: ReducedModel) -> dict:
    """Create, test and publish the Studio calculation; Studio's guards refuse a failing report."""
    contract, source, tests = studio_contract(model), studio_source(model), studio_tests(model)
    runtime = runtime_status()
    if not runtime["available"]:
        raise PublicationRefused([f"Studio runtime unavailable ({runtime['reason']}); nothing was created"])
    draft = studio.create(workspace_id, contract)
    studio.update(workspace_id, draft["id"], StudioUpdate(source=source, assumptions=provenance_note(model)))
    report = studio.test(workspace_id, draft["id"], tests)
    if not report["passed"]:
        errors = [error for case in report["cases"] for error in case["errors"]]
        raise PublicationRefused([f"Studio tests failed: {'; '.join(errors) or 'no detail'}"])
    version = studio.publish(workspace_id, draft["id"])
    return {**version, "reduced_model_id": model.model_id, "reduced_model_version_id": model.version_id,
            "geometry_digest": model.geometry_digest, "test_report": report}


def reduced_model_of_source(source: str) -> ReducedModel:
    """Read the pinned reduced model back from a published Studio source and check its identity."""
    marker = "REDUCED_MODEL_JSON = "
    line = next((row for row in source.splitlines() if row.startswith(marker)), None)
    if line is None:
        raise PublicationRefused(["source is not a generated reduced-model calculation"])
    model = ReducedModel.model_validate(json.loads(ast.literal_eval(line[len(marker):])))
    if not verify_version(model) or studio_source(model) != source:
        raise PublicationRefused(["source does not match the reduced model it carries"])
    return model
