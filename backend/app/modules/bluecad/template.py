"""Provider-free BLUECAD candidates from explicit operator template parameters.

A template maps a few bounded millimetre parameters onto one existing
GeometrySpec part kind and then follows the same canonicalization, build,
validation, evidence and export path as the AI loop. No AI call is made.
"""

from __future__ import annotations

import json
import math
from typing import Annotated, Any, Literal
from uuid import uuid4

from pydantic import BaseModel, ConfigDict, Field, model_validator

from app.core.database import open_sqlite_connection
from app.modules.bluecad.candidate_build import build_geometry_candidate
from app.modules.bluecad.ledger import (
    _require_workspace,
    brief_digest,
    get_candidate,
    park_candidate,
)
from app.modules.bluecad.models import BluecadCandidateRead
from app.modules.bluecad.service import DEFAULT_TIMEOUT_SECONDS
from app.modules.bluecad.spec import SpecValidationError, canonicalize_geometry_spec
from app.modules.events.service import utc_now

TEMPLATE_VERSION = "bluecad_template_v0_1"
ARTIFACT_PRODUCER = "Generated by deterministic BLUECAD template from explicit operator parameters."

_STRICT = ConfigDict(extra="forbid", allow_inf_nan=False)
OuterDiameterMm = Annotated[float, Field(ge=2.0, le=1000.0)]
WallMm = Annotated[float, Field(ge=0.5, le=100.0)]
LengthMm = Annotated[float, Field(ge=1.0, le=5000.0)]
SERPENTINE_MAX_SEGMENTS = 64
TEMPLATE_BUILD_TIMEOUT_CAP_S = 360.0


class TemplateError(ValueError):
    def __init__(self, code: str, message: str, *, status_code: int) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.status_code = status_code


class TubeTemplateParams(BaseModel):
    model_config = _STRICT

    outer_d_mm: OuterDiameterMm
    wall_t_mm: WallMm
    length_mm: LengthMm

    @model_validator(mode="after")
    def _wall_fits(self) -> TubeTemplateParams:
        if self.wall_t_mm * 2 >= self.outer_d_mm:
            raise ValueError("wall_t_mm must be less than half of outer_d_mm")
        return self


class ManifoldTemplateParams(BaseModel):
    model_config = _STRICT

    outer_d_mm: OuterDiameterMm
    wall_t_mm: WallMm
    length_mm: LengthMm
    branch_count: int = Field(ge=1, le=12, strict=True)
    branch_outer_d_mm: OuterDiameterMm

    @model_validator(mode="after")
    def _branches_fit(self) -> ManifoldTemplateParams:
        if self.wall_t_mm * 2 >= self.outer_d_mm:
            raise ValueError("wall_t_mm must be less than half of outer_d_mm")
        if self.wall_t_mm * 2 >= self.branch_outer_d_mm:
            raise ValueError("wall_t_mm must be less than half of branch_outer_d_mm")
        if self.branch_outer_d_mm >= self.outer_d_mm:
            raise ValueError("branch_outer_d_mm must be less than outer_d_mm")
        if self.branch_outer_d_mm >= self.length_mm / (self.branch_count + 1):
            raise ValueError("branches do not fit: branch_outer_d_mm must be less than length_mm / (branch_count + 1)")
        return self


class SerpentineTemplateParams(BaseModel):
    """Long loop as `segment_count` straight runs joined by 180-degree U-bends.

    Each run stays within the single-solid LengthMm limit; the loop is planar with
    runs parallel to x and spaced 2 * bend_radius_mm apart (centreline). The
    centreline radius must be at least one outer diameter, which also keeps
    adjacent runs a full outer diameter apart (2 * bend_radius > outer_d).
    """

    model_config = _STRICT

    outer_d_mm: OuterDiameterMm
    wall_t_mm: WallMm
    segment_length_mm: LengthMm
    segment_count: int = Field(ge=1, le=SERPENTINE_MAX_SEGMENTS, strict=True)
    bend_radius_mm: float = Field(ge=1.0, le=5000.0)

    @model_validator(mode="after")
    def _loop_fits(self) -> SerpentineTemplateParams:
        if self.wall_t_mm * 2 >= self.outer_d_mm:
            raise ValueError("wall_t_mm must be less than half of outer_d_mm")
        if self.bend_radius_mm < self.outer_d_mm:
            raise ValueError("bend_radius_mm must be at least outer_d_mm")
        return self

    @property
    def centreline_length_mm(self) -> float:
        return self.segment_count * self.segment_length_mm + (self.segment_count - 1) * math.pi * self.bend_radius_mm


class TubeTemplateCreate(BaseModel):
    model_config = _STRICT

    template: Literal["tube"]
    params: TubeTemplateParams


class ManifoldTemplateCreate(BaseModel):
    model_config = _STRICT

    template: Literal["manifold"]
    params: ManifoldTemplateParams


class SerpentineTemplateCreate(BaseModel):
    model_config = _STRICT

    template: Literal["serpentine"]
    params: SerpentineTemplateParams


TemplateCreate = TubeTemplateCreate | ManifoldTemplateCreate | SerpentineTemplateCreate
BluecadTemplateCreate = Annotated[TemplateCreate, Field(discriminator="template")]


def _serpentine_parts(p: SerpentineTemplateParams) -> tuple[list[dict[str, Any]], list[dict[str, str]]]:
    """Runs and U-bends chained by connections; the assembler derives the placement.

    A bend always turns left from port_a to port_b, so every second bend is
    joined by its port_b to the preceding run, which turns the loop the other way.
    """

    common = {"outer_d": p.outer_d_mm, "wall_t": p.wall_t_mm}
    parts: list[dict[str, Any]] = []
    connections: list[dict[str, str]] = []
    for index in range(1, p.segment_count + 1):
        parts.append({"part_id": f"run_{index}", "kind": "tube_run", "params": {**common, "length": p.segment_length_mm}})
        if index == p.segment_count:
            break
        parts.append({"part_id": f"bend_{index}", "kind": "bend",
                      "params": {**common, "bend_radius": p.bend_radius_mm, "angle": math.pi}})
        near, far = ("port_a", "port_b") if index % 2 else ("port_b", "port_a")
        connections.append({"from": f"run_{index}.port_b", "to": f"bend_{index}.{near}"})
        connections.append({"from": f"bend_{index}.{far}", "to": f"run_{index + 1}.port_a"})
    return parts, connections


def template_geometry_spec(payload: TemplateCreate) -> dict[str, Any]:
    """Return the canonical GeometrySpec for one validated template request."""

    if isinstance(payload, TubeTemplateCreate):
        p = payload.params
        part = {
            "part_id": "template_tube",
            "kind": "tube_run",
            "params": {"outer_d": p.outer_d_mm, "wall_t": p.wall_t_mm, "length": p.length_mm},
        }
    elif isinstance(payload, SerpentineTemplateCreate):
        parts, connections = _serpentine_parts(payload.params)
        return _canonical({"spec_version": "bluecad_geometry_spec_v0_1", "name": "template_serpentine",
                           "parts": parts, "connections": connections})
    else:
        m = payload.params
        part = {
            "part_id": "template_manifold",
            "kind": "manifold",
            "params": {
                "outer_d_main": m.outer_d_mm,
                "wall_t": m.wall_t_mm,
                "length": m.length_mm,
                "n_out": m.branch_count,
                "out_d": m.branch_outer_d_mm,
                "out_wall_t": m.wall_t_mm,
                # Branches are spread evenly along the header.
                "spacing": m.length_mm / (m.branch_count + 1),
            },
        }
    raw_spec = {
        "spec_version": "bluecad_geometry_spec_v0_1",
        "name": f"template_{payload.template}",
        "parts": [part],
        "connections": [],
    }
    return _canonical(raw_spec)


def template_build_timeout_s(spec: dict[str, Any]) -> float:
    """Build budget that scales with part count: a 64-run serpentine has 127 solids, about 1-2 s each."""

    return min(TEMPLATE_BUILD_TIMEOUT_CAP_S, max(DEFAULT_TIMEOUT_SECONDS, 10.0 + 2.5 * len(spec["parts"])))


def _canonical(raw_spec: dict[str, Any]) -> dict[str, Any]:
    try:
        return canonicalize_geometry_spec(raw_spec)
    except SpecValidationError as exc:
        raise TemplateError(
            "template_geometry_invalid", "Template parameters do not form a valid GeometrySpec.", status_code=422
        ) from exc


def _brief(payload: TemplateCreate) -> str:
    if isinstance(payload, TubeTemplateCreate):
        p = payload.params
        return f"Template tube: outer Ø {p.outer_d_mm:g} mm, wall {p.wall_t_mm:g} mm, length {p.length_mm:g} mm."
    if isinstance(payload, SerpentineTemplateCreate):
        s = payload.params
        return (
            f"Template serpentine: outer Ø {s.outer_d_mm:g} mm, wall {s.wall_t_mm:g} mm, {s.segment_count} × "
            f"{s.segment_length_mm:g} mm runs, bend radius {s.bend_radius_mm:g} mm, "
            f"centreline {s.centreline_length_mm:g} mm."
        )
    m = payload.params
    return (
        f"Template manifold: header Ø {m.outer_d_mm:g} mm, wall {m.wall_t_mm:g} mm, length {m.length_mm:g} mm, "
        f"{m.branch_count} × Ø {m.branch_outer_d_mm:g} mm branches."
    )


def create_template_candidate(workspace_id: str, payload: TemplateCreate) -> BluecadCandidateRead:
    """Create, build and validate one deterministic template candidate."""

    spec = template_geometry_spec(payload)
    candidate_id = str(uuid4())
    attempt_id = str(uuid4())
    now = utc_now()
    brief = _brief(payload)
    route_class = f"deterministic:template:{payload.template}"
    with open_sqlite_connection() as connection:
        try:
            _require_workspace(connection, workspace_id)
        except ValueError as exc:
            raise TemplateError("workspace_not_found", "Workspace not found.", status_code=404) from exc
        connection.execute(
            """
            INSERT INTO bluecad_candidates (
                id, workspace_id, brief_text, brief_digest, status, parked_reason,
                spec_artifact_id, glb_artifact_id, report_artifact_id,
                promoted_decision_id, origin, parent_candidate_id,
                loop_config_json, created_at, updated_at, notes
            ) VALUES (?, ?, ?, ?, 'generating', NULL, NULL, NULL, NULL, NULL,
                'template', NULL, '{}', ?, ?, ?)
            """,
            (
                candidate_id,
                workspace_id,
                brief,
                brief_digest(brief),
                now,
                now,
                f"template_version={TEMPLATE_VERSION}; template={payload.template}",
            ),
        )
        connection.execute(
            """
            INSERT INTO bluecad_attempts (
                id, candidate_id, attempt_no, route_class, proposal_ai_job_id,
                proposal_outcome, build_outcome, validation_verdict,
                spec_artifact_id, report_artifact_id, manifest_artifact_id,
                started_at, finished_at, error_detail_json
            ) VALUES (?, ?, 1, ?, NULL, 'not_applicable', NULL, NULL, NULL, NULL, NULL, ?, NULL, ?)
            """,
            (
                attempt_id,
                candidate_id,
                route_class,
                now,
                json.dumps(
                    {"template_version": TEMPLATE_VERSION, "params": payload.params.model_dump()}, sort_keys=True
                ),
            ),
        )
        connection.commit()

    try:
        build_geometry_candidate(
            workspace_id,
            candidate_id,
            attempt_id,
            spec,
            producer_notes=ARTIFACT_PRODUCER,
            failure_reason="template_build_failed",
            timeout_s=template_build_timeout_s(spec),
        )
    except Exception as exc:
        park_candidate(candidate_id, "template_build_failed", notes=f"template_execution_error={type(exc).__name__}")
        raise TemplateError(
            "template_build_failed",
            "The deterministic template build did not complete coherently.",
            status_code=500,
        ) from exc

    candidate = get_candidate(workspace_id, candidate_id)
    if candidate is None:  # pragma: no cover - defensive persistence guard
        raise TemplateError("template_persistence_inconsistent", "Template candidate is missing.", status_code=500)
    return candidate
