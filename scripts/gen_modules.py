#!/usr/bin/env python3
"""Generate docs/MODULES.md from the module.toml files (deterministic; CI fails if the committed file differs).

Every module directory under backend/app/modules, plus backend/app/core and the other areas below, carries a
module.toml with: purpose (1-2 lines), status (live | in-development | backlog-candidate), entrypoints (list of
route prefixes or files) and owner. A module directory without one is an error, so the map cannot silently rot.

    python scripts/gen_modules.py            # rewrite docs/MODULES.md
    python scripts/gen_modules.py --check    # exit 1 if docs/MODULES.md is stale
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "MODULES.md"
STATUSES = ("live", "in-development", "backlog-candidate")
REQUIRED = ("purpose", "status", "entrypoints", "owner")
# Directories whose every child directory must declare a module.toml.
REQUIRED_PARENTS = ("backend/app/modules",)
CODE_SUFFIXES = {".py", ".ts", ".tsx", ".js", ".mjs", ".css", ".sh", ".ps1"}
SKIPPED_DIRS = {"__pycache__", "node_modules", ".venv", "dist", ".git", ".pytest_cache", ".mypy_cache", ".ruff_cache"}


def _is_skipped(path: Path) -> bool:
    return path.name in SKIPPED_DIRS or path.name.startswith(".")


def find_manifests(root: Path = ROOT) -> list[Path]:
    found: list[Path] = []
    stack = [root]
    while stack:
        directory = stack.pop()
        for child in directory.iterdir():
            if child.is_dir() and not _is_skipped(child):
                stack.append(child)
            elif child.name == "module.toml" and child.is_file():
                found.append(child)
    return sorted(found)


def load_manifest(path: Path, root: Path = ROOT) -> dict:
    rel = path.parent.relative_to(root).as_posix() or "."
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    missing = [key for key in REQUIRED if key not in data]
    if missing:
        raise ValueError(f"{rel}/module.toml: missing {', '.join(missing)}")
    if data["status"] not in STATUSES:
        raise ValueError(f"{rel}/module.toml: status must be one of {', '.join(STATUSES)}")
    if not isinstance(data["entrypoints"], list) or not all(isinstance(item, str) for item in data["entrypoints"]):
        raise ValueError(f"{rel}/module.toml: entrypoints must be a list of strings")
    if not str(data["purpose"]).strip():
        raise ValueError(f"{rel}/module.toml: purpose is empty")
    return {**data, "path": rel}


def count_lines(directory: Path, nested: set[Path]) -> int:
    """Physical lines of code files under directory, not counting nested directories that have their own manifest."""
    total = 0
    stack = [directory]
    while stack:
        current = stack.pop()
        for child in current.iterdir():
            if child.is_dir():
                if not _is_skipped(child) and child not in nested:
                    stack.append(child)
            elif child.suffix in CODE_SUFFIXES:
                with child.open("rb") as handle:
                    total += sum(1 for _ in handle)
    return total


def loc_label(lines: int) -> str:
    """Rounded to 100 so that ordinary edits do not make the committed table stale."""
    return "<100" if lines < 100 else str(int(round(lines, -2)))


def missing_manifests(root: Path = ROOT) -> list[str]:
    missing: list[str] = []
    for parent in REQUIRED_PARENTS:
        base = root / parent
        for child in sorted(base.iterdir()):
            if child.is_dir() and not _is_skipped(child) and not (child / "module.toml").is_file():
                missing.append(child.relative_to(root).as_posix())
    return missing


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render(root: Path = ROOT) -> str:
    missing = missing_manifests(root)
    if missing:
        raise ValueError("directories without a module.toml: " + ", ".join(missing))
    manifests = [load_manifest(path, root) for path in find_manifests(root)]
    directories = {root / entry["path"] for entry in manifests}
    lines = [
        "# Modules",
        "",
        "Generated by `scripts/gen_modules.py` from the `module.toml` file in each module directory. Do not edit; change the",
        "`module.toml` and rerun the script. CI fails when this file is stale. Status: `live` is reachable from the running",
        "app or a supported tool; `in-development` is being built toward a decided direction; `backlog-candidate` has no",
        "current consumer and should be implemented, rethought or deleted. LOC counts code files in the directory, not in",
        "nested modules listed separately, rounded to the nearest 100.",
        "",
        "| Path | Status | Purpose | Entrypoints | LOC |",
        "| --- | --- | --- | --- | ---: |",
    ]
    for entry in sorted(manifests, key=lambda item: item["path"]):
        nested = {d for d in directories if d != root / entry["path"]}
        loc = count_lines(root / entry["path"], nested)
        entrypoints = ", ".join(f"`{_cell(item)}`" for item in entry["entrypoints"])
        lines.append(
            f"| `{entry['path']}` | {entry['status']} | {_cell(entry['purpose'])} | {entrypoints} | {loc_label(loc)} |"
        )
    counts = {status: sum(1 for entry in manifests if entry["status"] == status) for status in STATUSES}
    lines += ["", "Totals: " + ", ".join(f"{counts[status]} {status}" for status in STATUSES) + ".", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    try:
        text = render()
    except ValueError as exc:
        print(f"gen_modules: {exc}", file=sys.stderr)
        return 1
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("gen_modules: docs/MODULES.md is stale; run python scripts/gen_modules.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
